// Turns drizzle-kit's generated SQL files (./drizzle/*.sql) into a TypeScript
// module so migrations ship inside the server bundle (no filesystem access
// needed on Vercel). Run via `npm run db:generate`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { join } from "node:path"

const dir = "drizzle"
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()

const migrations = files.map((file) => ({
  name: file.replace(/\.sql$/, ""),
  statements: readFileSync(join(dir, file), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean),
}))

const out = `// AUTO-GENERATED by scripts/db/embed-migrations.mjs — do not edit by hand.
// Source: ./drizzle/*.sql (generated by drizzle-kit from src/lib/db/schema.ts)

export type EmbeddedMigration = { readonly name: string; readonly statements: readonly string[] }

export const migrations: readonly EmbeddedMigration[] = ${JSON.stringify(migrations, null, 2)}
`

writeFileSync("src/lib/db/migrations.generated.ts", out)
console.log(`Embedded ${migrations.length} migration(s): ${migrations.map((m) => m.name).join(", ")}`)
